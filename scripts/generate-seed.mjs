/**
 * Generates supabase/seed.sql from src/content/local/data.ts (single source for demo content).
 * Run: npm run seed:generate   (Node 22 --experimental-strip-types)
 * Bundled placeholder photos are referenced as "local:<manifest-key>" so no upload is needed.
 */
import { writeFile } from 'node:fs/promises'
import { aboutContent, categories, projects, services, siteSettings } from '../src/content/local/data.ts'

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`
const lines = ['-- Generated by scripts/generate-seed.mjs. Do not edit by hand.', '-- PLACEHOLDER content: every project/service is flagged is_placeholder = true.', 'begin;', '']

for (const c of categories) {
  lines.push(`insert into public.categories (slug, label, sort_order) values (${q(c.slug)}, ${q(c.label)}, ${c.order}) on conflict (slug) do nothing;`)
}
lines.push('')

projects.forEach((p, i) => {
  const cat = categories.find((c) => c.id === p.categoryId)
  lines.push(
    `insert into public.projects (slug, title, category_id, summary, description, location, year, area_sqm, status, featured, featured_order, is_placeholder, sort_order)`,
    `select ${q(p.slug)}, ${q(p.title)}, c.id, ${q(p.summary)}, ${arr(p.description)}, ${q(p.location)}, ${p.year ?? 'null'}, ${p.areaSqm ?? 'null'}, ${q(p.status)}, ${p.featured}, ${p.featuredOrder ?? 'null'}, ${p.isPlaceholder}, ${i + 1}`,
    `from public.categories c where c.slug = ${q(cat.slug)} on conflict (slug) do nothing;`,
  )
  const images = [
    ...p.gallery.map((g) => ({ ...g, kind: 'photo' })),
    ...p.drawings.filter((d) => !d.src.startsWith('plan:')).map((d) => ({ ...d, kind: 'drawing' })),
  ]
  images.forEach((img, k) => {
    lines.push(
      `insert into public.project_images (project_id, storage_path, alt, kind, sort_order) select id, ${q('local:' + img.src)}, ${q(img.alt)}, ${q(img.kind)}, ${k} from public.projects where slug = ${q(p.slug)} and not exists (select 1 from public.project_images pi join public.projects pp on pp.id = pi.project_id where pp.slug = ${q(p.slug)} and pi.storage_path = ${q('local:' + img.src)});`,
    )
  })
  lines.push(
    `update public.projects pr set cover_image_id = (select pi.id from public.project_images pi where pi.project_id = pr.id and pi.storage_path = ${q('local:' + p.cover.src)} order by pi.sort_order limit 1) where pr.slug = ${q(p.slug)} and pr.cover_image_id is null;`,
    '',
  )
})

for (const s of services) {
  lines.push(
    `insert into public.services (slug, title, summary, body, includes, image_path, image_alt, sort_order, is_placeholder) values (${q(s.slug)}, ${q(s.title)}, ${q(s.summary)}, ${arr(s.body)}, ${arr(s.includes)}, ${q('local:' + s.image.src)}, ${q(s.image.alt)}, ${s.order}, ${s.isPlaceholder}) on conflict (slug) do nothing;`,
  )
}
lines.push('')

const about = { ...aboutContent }
lines.push(`insert into public.page_content (key, content) values ('about', ${q(JSON.stringify(about))}::jsonb) on conflict (key) do nothing;`, '')

const s = siteSettings
lines.push(
  `update public.site_settings set studio_name = ${q(s.studioName)}, tagline = ${q(s.tagline)}, architect_name = ${q(s.architectName)}, architect_role = ${q(s.architectRole)}, email = ${q(s.email)}, phone = ${q(s.phone)}, address = ${q(s.address)}, instagram = ${q(s.instagram)}, seo_title = ${q(s.seo.title)}, seo_description = ${q(s.seo.description)} where id = 1;`,
  '',
  'commit;',
  '',
)

await writeFile('supabase/seed.sql', lines.join('\n'))
console.log(`supabase/seed.sql: ${categories.length} categories, ${projects.length} projects, ${services.length} services`)
