test('create, upload, require alt text, publish', async ({ page }) => {
  await login(page)
  await page.goto('/diaxeirisi/erga/neo')
  await expect(page.locator('h1')).toHaveText('Νέο έργο')
  await page.locator('input').first().fill('Δοκιμαστικό Έργο Ξενώνα')
  await expect(page.locator('input').nth(1)).toHaveValue('dokimastiko-ergo-xenona')
  await page.getByRole('button', { name: 'Δημιουργία έργου' }).click()
  await expect(page).toHaveURL(/\/diaxeirisi\/erga\/(?!neo)[\w-]+$/)
  await page.setInputFiles('input[type="file"]', path.join(import.meta.dirname, '../fixtures/photo.jpg'))
  await expect(page.getByText('· λείπει')).toBeVisible({ timeout: 15_000 })
  await page.locator('[role="switch"]').first().click()
  await page.getByRole('button', { name: 'Αποθήκευση', exact: true }).click()
  await expect(page.getByText('συμπληρώστε περιγραφή (alt)')).toBeVisible()
  await page.locator('input[id^="alt-"]').fill('Σύγχρονη κατοικία κάτω από μεγάλο δέντρο')
  await page.locator('input[id^="alt-"]').blur()
  await page.getByRole('button', { name: 'Αποθήκευση', exact: true }).click()
  await expect(page.getByText('είναι δημοσιευμένο')).toBeVisible()
  await page.goto('/erga/dokimastiko-ergo-xenona')
  await expect(page.locator('h1')).toHaveText('Δοκιμαστικό Έργο Ξενώνα')
  await expect.poll(() => page.evaluate(() => [...document.images].some((i) => i.currentSrc.startsWith('data:image/webp') && i.naturalWidth > 0))).toBe(true)
})

test('categories in use cannot be deleted; settings reach the site', async ({ page }) => {
  await login(page)
  await page.goto('/diaxeirisi/katigories')
  await expect(page.locator('li:has(input[value="katoikies"])').getByRole('button', { name: 'Διαγραφή' })).toBeDisabled()
  await page.goto('/diaxeirisi/rythmiseis')
  await page.getByLabel('Ονοματεπώνυμο αρχιτέκτονα').fill('Όνομα Δοκιμής')
  await page.getByLabel('Email').fill('info@example.gr')
  await page.getByLabel('Τηλέφωνο').fill('+30 690 000 0000')
  await page.getByRole('button', { name: 'Αποθήκευση', exact: true }).click()
  await expect(page.getByText('αποθηκεύτηκαν')).toBeVisible()
  await page.goto('/sxetika')
  await expect(page.locator('h1')).toHaveText('Όνομα Δοκιμής')
  // Contact details from the CMS replace the footer's «coming soon» text.
  const footer = page.locator('footer')
  await expect(footer.getByRole('link', { name: 'info@example.gr' })).toHaveAttribute('href', 'mailto:info@example.gr')
  await expect(footer.getByRole('link', { name: '+30 690 000 0000' })).toHaveAttribute('href', 'tel:+306900000000')
  await expect(footer).not.toContainText('θα προστεθούν σύντομα')
  // Sample photos are still in use, so the note stays.
  await expect(footer).toContainText('ενδεικτικές (Unsplash)')
})

test('replace the home hero photo; the sample label disappears', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('#arxi picture img')).toHaveAttribute('src', /hero-dusk-villa/)
  await login(page)
  await page.locator('nav[aria-label="Διαχείριση"]').getByText('Αρχική σελίδα').click()
  await expect(page.locator('h1')).toHaveText('Αρχική σελίδα')
  const hero = page.locator('[data-home-slot="hero"]')
  await expect(hero.getByText('Τώρα: ενδεικτική φωτογραφία.')).toBeVisible()
  await hero.locator('input[type="file"]').setInputFiles(path.join(import.meta.dirname, '../fixtures/photo.jpg'))
  await expect(hero.getByRole('button', { name: 'Επαναφορά ενδεικτικής' })).toBeVisible({ timeout: 15_000 })
  // The sample's description no longer applies: a new one is required.
  await expect(hero.locator('textarea')).toHaveValue('')
  await page.getByRole('button', { name: 'Αποθήκευση', exact: true }).click()
  await expect(page.getByText('Συμπληρώστε την περιγραφή (alt)')).toBeVisible()
  await hero.locator('textarea').fill('Η νέα κατοικία της αρχιτέκτονα στο φως του απογεύματος')
  await page.getByRole('button', { name: 'Αποθήκευση', exact: true }).click()
  await expect(page.getByText('Οι φωτογραφίες της αρχικής αποθηκεύτηκαν')).toBeVisible()

  await page.goto('/')
  const img = page.locator('#arxi picture img')
  await expect(img).toHaveAttribute('alt', 'Η νέα κατοικία της αρχιτέκτονα στο φως του απογεύματος')
  await expect(img).toHaveAttribute('src', /^data:image\//)
  await expect(page.locator('[data-hero-caption]')).not.toContainText('Ενδεικτική')
  // Other sections still show (and label) their sample photos.
  await expect(page.locator('#filosofia figcaption')).toContainText('Ενδεικτική φωτογραφία')
})
